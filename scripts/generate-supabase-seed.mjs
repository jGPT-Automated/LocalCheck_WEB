import { readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const rows = JSON.parse(await readFile(resolve(root, "data/launch-courts.json"), "utf8"));
const output = resolve(root, "supabase/seed.sql");

const quote = (value) => value === null || value === undefined || value === ""
  ? "null"
  : `'${String(value).replaceAll("'", "''")}'`;
const number = (value) => value === null || value === undefined || value === "" ? "null" : String(value);
const bool = (value) => value === null || value === undefined ? "null" : value ? "true" : "false";

const values = rows.map((row) => `  (
    ${quote(row.slug)}, ${quote(row.name)}, ${quote(row.short_name)}, ${quote(row.address)},
    ${quote(row.city)}, ${quote(row.state)}, ${quote(row.postal_code)}, ${quote(row.market)}, ${quote(row.city)},
    ${number(row.latitude)}, ${number(row.longitude)}, ${quote(row.sport)}, ${quote(row.access_type)}, ${quote(row.setting)},
    ${number(row.court_count)}, ${quote(row.launch_reason)}, ${number(row.launch_priority)}, ${quote(row.verification_status)},
    ${quote(row.source_url)}, ${quote(row.source_tier)}, ${quote(row.geocode_source)}, ${quote(row.geocode_query)},
    ${quote(row.detection_source_id)}, ${number(row.detection_distance_m)}, ${quote(row.satellite_match_status)},
    ${bool(row.setting === "indoor" ? true : row.setting === "outdoor" || row.setting === "outdoor_covered" ? false : null)}
  )`).join(",\n");

const sql = `-- Generated by scripts/generate-supabase-seed.mjs from data/launch-courts.json.
-- Re-running is safe: slug is the stable import key.
insert into public.courts (
  slug, name, short_name, address, city, state, postal_code, market, location,
  latitude, longitude, sport_type, access_type, setting, court_count,
  launch_reason, launch_priority, verification_status, source_url, source_tier,
  geocode_source, geocode_query, detection_source_id, detection_distance_m,
  satellite_match_status, indoor
)
values
${values}
on conflict (slug) do update set
  name = excluded.name,
  short_name = excluded.short_name,
  address = excluded.address,
  city = excluded.city,
  state = excluded.state,
  postal_code = excluded.postal_code,
  market = excluded.market,
  location = excluded.location,
  latitude = excluded.latitude,
  longitude = excluded.longitude,
  sport_type = excluded.sport_type,
  access_type = excluded.access_type,
  setting = excluded.setting,
  court_count = excluded.court_count,
  launch_reason = excluded.launch_reason,
  launch_priority = excluded.launch_priority,
  verification_status = excluded.verification_status,
  source_url = excluded.source_url,
  source_tier = excluded.source_tier,
  geocode_source = excluded.geocode_source,
  geocode_query = excluded.geocode_query,
  detection_source_id = excluded.detection_source_id,
  detection_distance_m = excluded.detection_distance_m,
  satellite_match_status = excluded.satellite_match_status,
  indoor = excluded.indoor,
  is_archived = false;
`;

await mkdir(dirname(output), { recursive: true });
await writeFile(output, sql);
console.log(`Wrote ${rows.length} courts to ${output}`);

